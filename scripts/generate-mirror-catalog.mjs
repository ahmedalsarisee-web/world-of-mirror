import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildCatalogSections, listCatalogSourceFiles, resolveCatalogSource, toWebpBasename} from './mirror-catalog-utils.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(__dirname, '..');
const catalogOutputRoot = path.join(projectRoot, 'assets', 'mirror-catalog');
const manifestPath = path.join(catalogOutputRoot, 'manifest.json');
const dataOutputFile = path.join(projectRoot, 'src', 'data', 'mirrorCatalogImages.ts');
const assetsOutputFile = path.join(projectRoot, 'src', 'data', 'mirrorCatalogImageAssets.ts');

function loadManifest() {
  if (!fs.existsSync(manifestPath)) {
    console.error('Missing assets/mirror-catalog/manifest.json — run: npm run optimize:mirror-catalog');
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
}

function buildRequireMap(entries, prefix) {
  return entries.map((entry) => {
    const webpName = entry.webpName ?? toWebpBasename(entry.id);
    return `  ${JSON.stringify(entry.id)}: require('${prefix}/${webpName.replace(/\\/g, '/')}'),`;
  });
}

function buildNaturalSizeMap(entries) {
  return entries
    .map(
      (entry) =>
        `  ${JSON.stringify(entry.id)}: {width: ${entry.displayWidth}, height: ${entry.displayHeight}},`,
    )
    .join('\n');
}

function verifyOptimizedAssets(entries) {
  const missing = [];

  for (const entry of entries) {
    const webpName = entry.webpName ?? toWebpBasename(entry.id);
    const thumbPath = path.join(catalogOutputRoot, 'thumbs', webpName);
    const displayPath = path.join(catalogOutputRoot, 'display', webpName);

    if (!fs.existsSync(thumbPath)) {
      missing.push(thumbPath);
    }
    if (!fs.existsSync(displayPath)) {
      missing.push(displayPath);
    }
  }

  if (missing.length > 0) {
    console.error('Missing optimized catalog files:');
    for (const file of missing.slice(0, 10)) {
      console.error(`  - ${path.relative(projectRoot, file)}`);
    }
    if (missing.length > 10) {
      console.error(`  ... and ${missing.length - 10} more`);
    }
    console.error('Run: npm run prepare:mirror-catalog:force');
    process.exit(1);
  }
}

function main() {
  const resolvedSource = resolveCatalogSource(projectRoot, fs);
  if (!resolvedSource) {
    console.error('No catalog source images found in "all mirror" or assets/all-mirror');
    process.exit(1);
  }

  const imageFiles = listCatalogSourceFiles(resolvedSource.dir, fs);
  const manifest = loadManifest();
  const manifestById = new Map(manifest.entries.map((entry) => [entry.id, entry]));

  const missingOptimized = imageFiles.filter((file) => !manifestById.has(file));
  if (missingOptimized.length > 0) {
    console.error('Missing optimized assets for:', missingOptimized.join(', '));
    console.error('Run: npm run optimize:mirror-catalog');
    process.exit(1);
  }

  const entries = imageFiles.map((file) => manifestById.get(file));
  verifyOptimizedAssets(entries);

  const catalogSections = buildCatalogSections(imageFiles);
  const thumbRequireLines = buildRequireMap(entries, '../../assets/mirror-catalog/thumbs');
  const displayRequireLines = buildRequireMap(entries, '../../assets/mirror-catalog/display');

  const dataContent = `/* eslint-disable @typescript-eslint/no-require-imports */
// Generated by scripts/generate-mirror-catalog.mjs — do not edit by hand.
// Source images: all mirror/ (then npm run prepare:mirror-catalog)

export const MIRROR_CATALOG_IMAGE_IDS = ${JSON.stringify(imageFiles, null, 2)} as const;

export type MirrorCatalogImageId = (typeof MIRROR_CATALOG_IMAGE_IDS)[number];

export interface MirrorCatalogSection {
  key: string;
  imageIds: MirrorCatalogImageId[];
}

export const MIRROR_CATALOG_SECTIONS: MirrorCatalogSection[] = ${JSON.stringify(catalogSections, null, 2)};

const MIRROR_CATALOG_NATURAL_SIZES: Record<MirrorCatalogImageId, {width: number; height: number}> = {
${buildNaturalSizeMap(entries)}
};

export function isMirrorCatalogImageId(value: string): value is MirrorCatalogImageId {
  return (MIRROR_CATALOG_IMAGE_IDS as readonly string[]).includes(value);
}

export function getMirrorCatalogImageNaturalSize(
  imageId: string,
): {width: number; height: number} | null {
  if (!isMirrorCatalogImageId(imageId)) {
    return null;
  }
  return MIRROR_CATALOG_NATURAL_SIZES[imageId] ?? null;
}

export function normalizeMirrorCatalogImageIds(values: unknown): MirrorCatalogImageId[] {
  if (!Array.isArray(values)) {
    return [];
  }

  const allowed = new Set<string>(MIRROR_CATALOG_IMAGE_IDS);
  const seen = new Set<string>();
  const normalized: MirrorCatalogImageId[] = [];

  for (const value of values) {
    if (typeof value !== 'string' || !allowed.has(value) || seen.has(value)) {
      continue;
    }
    seen.add(value);
    normalized.push(value as MirrorCatalogImageId);
  }

  return normalized;
}
`;

  const assetsContent = `/* eslint-disable @typescript-eslint/no-require-imports */
// Generated by scripts/generate-mirror-catalog.mjs — do not edit by hand.

import {Image, type ImageSourcePropType} from 'react-native';
import {isMirrorCatalogImageId, type MirrorCatalogImageId} from '@app/data/mirrorCatalogImages';

const MIRROR_CATALOG_THUMB_SOURCES: Record<MirrorCatalogImageId, ImageSourcePropType> = {
${thumbRequireLines.join('\n')}
};

const MIRROR_CATALOG_DISPLAY_SOURCES: Record<MirrorCatalogImageId, ImageSourcePropType> = {
${displayRequireLines.join('\n')}
};

export function getMirrorCatalogThumbSource(imageId: string): ImageSourcePropType | null {
  if (!isMirrorCatalogImageId(imageId)) {
    return null;
  }
  return MIRROR_CATALOG_THUMB_SOURCES[imageId];
}

export function getMirrorCatalogDisplaySource(imageId: string): ImageSourcePropType | null {
  if (!isMirrorCatalogImageId(imageId)) {
    return null;
  }
  return MIRROR_CATALOG_DISPLAY_SOURCES[imageId];
}

/** Full-quality display asset (preview, text editor, export). */
export function getMirrorCatalogImageSource(imageId: string): ImageSourcePropType | null {
  return getMirrorCatalogDisplaySource(imageId);
}

export function getMirrorCatalogImageUri(imageId: string): string | null {
  const source = getMirrorCatalogDisplaySource(imageId);
  if (!source) {
    return null;
  }
  const resolved = Image.resolveAssetSource(source);
  return resolved?.uri ?? null;
}
`;

  fs.mkdirSync(path.dirname(dataOutputFile), {recursive: true});
  fs.writeFileSync(dataOutputFile, dataContent, 'utf8');
  fs.writeFileSync(assetsOutputFile, assetsContent, 'utf8');
  console.log(
    `Wrote ${imageFiles.length} catalog images to ${path.relative(projectRoot, dataOutputFile)} + assets module`,
  );
}

main();
